"""Command line: ``python -m tools.pine2py input.pine -o dashboard/indicators_ext/<name>.py [--name x] [--print]``."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from . import GENERATED_MARKER, convert
from .errors import PineError, format_error


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tools.pine2py",
                                     description="Convert a Pine Script (v4/v5) indicator into a dashboard indicator plugin.")
    parser.add_argument("input", help="the .pine file to convert ('-' reads standard input)")
    parser.add_argument("-o", "--output", help="where to write the plugin, e.g. dashboard/indicators_ext/my_indicator.py")
    parser.add_argument("--name", help="plugin name (default: derived from the script title)")
    parser.add_argument("--print", dest="show", action="store_true", help="print the generated code")
    parser.add_argument("--force", action="store_true", help="overwrite an output file that was not generated by this tool")
    args = parser.parse_args(argv)

    if args.input == "-":
        source = sys.stdin.read()
    else:
        try:
            source = Path(args.input).read_text(encoding="utf-8-sig")
        except OSError as exc:
            print(f"error: cannot read {args.input}: {exc}", file=sys.stderr)
            return 2
    try:
        result = convert(source, args.name)
    except PineError as exc:
        print(format_error(source, exc, args.input), file=sys.stderr)
        return 1
    for warning in result.warnings:
        print(f"warning: {warning}".encode("ascii", "replace").decode("ascii"), file=sys.stderr)
    if args.output:
        out = Path(args.output)
        if out.exists() and not args.force:
            head = out.read_text(encoding="utf-8", errors="replace")[:200]
            if GENERATED_MARKER not in head:
                print(f"error: {out} exists and was not generated by this tool; use --force to overwrite it", file=sys.stderr)
                return 1
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(result.code, encoding="utf-8", newline="\n")
        print(f"wrote {out} ({result.name}: {result.title})")
    if args.show or not args.output:
        sys.stdout.write(result.code)
    return 0


if __name__ == "__main__":
    sys.exit(main())
