"""Pine Script (TradingView) to dashboard indicator converter.

``convert(source, name=None)`` returns a ``ConvertResult`` whose ``code`` is a Python module that
follows the plugin contract in ``dashboard/indicator_plugins.py``. Command line:

    python -m tools.pine2py input.pine -o dashboard/indicators_ext/<name>.py

The converter translates the user's own script; it never adds rules, levels or signals.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .errors import PineError, PineSyntaxError, format_error

__all__ = ["convert", "ConvertResult", "PineError", "PineSyntaxError", "format_error", "GENERATED_MARKER"]

GENERATED_MARKER = "# generated by tools.pine2py"


@dataclass
class ConvertResult:
    code: str
    warnings: list = field(default_factory=list)
    name: str = ""
    title: str = ""
    overlay: bool = False


def convert(source: str, name: str | None = None) -> ConvertResult:
    """Convert Pine Script source to plugin source. Raises PineSyntaxError(message, line, col)."""
    from .codegen import generate
    from .parser import parse

    script, lexed = parse(source)
    version = lexed.version
    warnings = []
    if version is not None and version < 4:
        warnings.append(f"//@version={version} is old; the script is read with Pine v4/v5 rules")
    code, gen_warnings, final_name, title, overlay = generate(script, version, name)
    return ConvertResult(code, warnings + gen_warnings, final_name, title, overlay)
