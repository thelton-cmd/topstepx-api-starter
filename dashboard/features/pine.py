"""Feature: "Pine Script to Python". Turns a TradingView Pine Script indicator into a dashboard
indicator plugin, using ``tools.pine2py``.

- ``POST /api/pine/convert`` ``{source, name?}``: ``{ok, name, title, code, warnings}``, or HTTP 400
  ``{error, line, col}`` when the script cannot be read or uses something unsupported.
- ``POST /api/pine/save`` ``{source, name}``: converts, imports the generated code in-process and
  runs it on a synthetic random walk (so a script that cannot load or compute is never written),
  then writes ``dashboard/indicators_ext/<name>.py``. The folder is hot-reloaded, so the indicator
  shows up in the chart's Indicators menu without a restart. A file that was not generated by this
  tool (it has no ``# generated by tools.pine2py`` first line) is never overwritten.
- ``GET /api/pine/examples``: the example scripts in ``tools/pine2py/examples``.

This converts the user's own script into lines on a chart. It never places or changes orders, adds
rules or levels, or describes anything as a signal; ``strategy()`` order logic is not converted.
"""

from __future__ import annotations

import os
import random
import re
import sys
import traceback
import types
from pathlib import Path

from .. import indicator_plugins

NAME = "pine"
TITLE = "Pine Script to Python"
DESCRIPTION = "Convert a TradingView Pine Script indicator into a dashboard indicator."
ORDER = 30
JS = "pine.js"
CSS = "pine.css"
# Pine scripts can be long (a few thousand lines is common); the server's default 64 KB POST cap is for order routes.
BODY_LIMITS = {"/api/pine/convert": 64 * 1024 * 1024, "/api/pine/save": 64 * 1024 * 1024}

NAME_PATTERN = re.compile(r"^[a-z][a-z0-9_]{0,39}$")
# No length cap of its own: the request body cap below (BODY_LIMITS) is the only bound.
GENERATED_MARKER = "# generated by tools.pine2py"

TARGET_DIR: Path = indicator_plugins.PLUGIN_DIR                       # tests point this at a temp folder
EXAMPLES_DIR: Path = Path(__file__).resolve().parents[2] / "tools" / "pine2py" / "examples"


def _ascii(text: str) -> str:
    return text.encode("ascii", "replace").decode("ascii")


def synthetic_candles(count: int = 300, seed: int = 5) -> list[dict]:
    """A deterministic random walk, only used to prove a converted script loads and computes."""
    rng = random.Random(seed)
    price, start = 100.0, 1_700_000_000
    out = []
    for i in range(count):
        o = price
        c = o + rng.gauss(0, 0.5)
        out.append({"time": start + 60 * i, "open": o, "high": max(o, c) + abs(rng.gauss(0, 0.2)),
                    "low": min(o, c) - abs(rng.gauss(0, 0.2)), "close": c, "volume": 100 + rng.randint(0, 50)})
        price = c
    return out


def _convert(source, name):
    from tools.pine2py import convert

    return convert(source, name)


def _body_source(body: dict) -> str:
    source = body.get("source") if isinstance(body, dict) else None
    if not isinstance(source, str) or not source.strip():
        raise ValueError("source must be the text of a Pine Script")
    return source


def _body_name(body: dict, required: bool) -> str | None:
    name = body.get("name")
    if name is None or (isinstance(name, str) and not name.strip()):
        if required:
            raise ValueError("name is required: a lowercase letter, then lowercase letters, digits or _ (40 characters at most)")
        return None
    if not isinstance(name, str) or not NAME_PATTERN.match(name.strip()):
        raise ValueError("name must start with a lowercase letter and contain only lowercase letters, digits and _ "
                         "(40 characters at most)")
    return name.strip()


def self_test(code: str) -> None:
    """Import generated code in-process (not registered anywhere) and run it on synthetic candles."""
    module = types.ModuleType("pine_selftest")
    try:
        exec(compile(code, "<converted pine script>", "exec"), module.__dict__)   # noqa: S102 - our own generator's output
        indicator_plugins._check_module(module)
        result = indicator_plugins.run(module, synthetic_candles(), {})
    except ImportError as exc:
        raise ValueError(f"the converted code could not import the converter runtime ({exc}); "
                         "run the dashboard from the kit's folder") from None
    except Exception as exc:  # noqa: BLE001 - reported to the user, never fatal
        raise ValueError(f"the converted code failed its test run: {type(exc).__name__}: {_ascii(str(exc))}") from None
    if not result["series"]:
        raise ValueError("the converted code produced no series")


def _convert_checked(source: str, name: str | None):
    """(ConvertResult, error response or None). A converter bug on odd input is a 400 too."""
    from tools.pine2py.errors import PineError

    try:
        return _convert(source, name), None
    except PineError as exc:
        return None, (400, {"error": exc.message, "line": exc.line, "col": exc.col})
    except RecursionError:
        return None, (400, {"error": "the script is nested too deeply to convert", "line": 0, "col": 0})
    except Exception as exc:  # noqa: BLE001
        traceback.print_exc(file=sys.stderr)
        return None, (400, {"error": f"the converter could not handle this script ({type(exc).__name__}: "
                                     f"{_ascii(str(exc))})", "line": 0, "col": 0})


def write_plugin(directory: Path, name: str, code: str) -> Path:
    """Write ``<name>.py`` atomically unless a file that this tool did not generate is in the way."""
    directory = Path(directory)
    target = directory / f"{name}.py"
    if target.exists():
        try:
            head = target.read_text(encoding="utf-8", errors="replace")[:200]
        except OSError as exc:
            raise ValueError(f"cannot read the existing {target.name}: {exc}") from None
        first_line = head.splitlines()[0] if head.strip() else ""
        if not first_line.startswith(GENERATED_MARKER):
            raise ValueError(f"{target.name} already exists and was not made by this converter; choose another name")
    directory.mkdir(parents=True, exist_ok=True)
    temp = directory / f".{name}.py.{os.getpid()}.tmp"
    temp.write_text(code, encoding="utf-8", newline="\n")
    os.replace(temp, target)
    return target


def routes(session) -> dict:
    def convert_route(body: dict) -> tuple[int, dict]:
        source = _body_source(body)
        name = _body_name(body, required=False)
        result, error = _convert_checked(source, name)
        if error is not None:
            return error
        warnings = list(result.warnings)
        try:
            self_test(result.code)
        except ValueError as exc:
            warnings.append(str(exc))
        return 200, {"ok": True, "name": result.name, "title": result.title, "code": result.code,
                     "overlay": result.overlay, "warnings": warnings}

    def save_route(body: dict) -> tuple[int, dict]:
        source = _body_source(body)
        name = _body_name(body, required=True)
        result, error = _convert_checked(source, name)
        if error is not None:
            return error
        self_test(result.code)
        target = write_plugin(TARGET_DIR, name, result.code)
        return 200, {"ok": True, "name": name, "path": str(target), "warnings": list(result.warnings)}

    def examples_route(query: dict) -> tuple[int, dict]:
        out = []
        try:
            files = sorted(EXAMPLES_DIR.glob("*.pine"))
        except OSError:
            files = []
        for path in files:
            try:
                text = path.read_text(encoding="utf-8")
            except OSError:
                continue
            m = re.search(r'(?:indicator|study|strategy)\(\s*"([^"]*)"', text)
            out.append({"name": path.stem, "title": m.group(1) if m else path.stem, "source": text})
        return 200, {"examples": out}

    return {"GET": {"/api/pine/examples": examples_route},
            "POST": {"/api/pine/convert": convert_route, "/api/pine/save": save_route}}
