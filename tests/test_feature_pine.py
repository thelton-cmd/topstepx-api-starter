"""Offline tests for the Pine Script to Python feature (dashboard/features/pine.py): the routes run on
the real test server (the ``dash`` fixture) and files are written to a temp folder, never into
dashboard/indicators_ext. Nothing here touches the network, an account or an order route."""

from __future__ import annotations

from pathlib import Path

import pytest

from dashboard import features as feature_registry
from dashboard import indicator_plugins
from dashboard.features import pine
from tests.test_dashboard_features import install
from tests.test_dashboard_server import as_json, dash, server_mod, static_dir  # noqa: F401 - fixtures

GOOD = '//@version=5\nindicator("Tiny SMA", overlay=true)\nlen = input.int(5, "Length", minval=1)\nplot(ta.sma(close, len), "SMA")\n'


@pytest.fixture
def pine_dash(dash, tmp_path, monkeypatch):
    target = tmp_path / "plugins"
    target.mkdir()
    monkeypatch.setattr(pine, "TARGET_DIR", target)
    install(dash.session, pine)
    dash.target = target
    return dash


def test_feature_is_discovered_with_its_page_module():
    assert pine in feature_registry.discover("pine")
    info = feature_registry.describe(pine)
    assert info == {"name": "pine", "title": "Pine Script to Python", "description": pine.DESCRIPTION,
                    "js": "pine.js", "css": "pine.css", "order": 30}
    static = Path(pine.__file__).resolve().parents[1] / "static" / "features"
    assert (static / "pine.js").is_file() and (static / "pine.css").is_file()
    assert not feature_registry.order_routes([pine])      # it never sends orders


def test_convert_ok(pine_dash):
    status, body, _ = pine_dash.post("/api/pine/convert", {"source": GOOD})
    data = as_json(body)
    assert status == 200 and data["ok"] is True
    assert data["name"] == "tiny_sma" and data["title"] == "Tiny SMA" and data["overlay"] is True
    assert data["code"].startswith("# generated by tools.pine2py from Tiny SMA - do not edit by hand")
    assert data["warnings"] == []
    # nothing is written by a plain convert
    assert list(pine_dash.target.iterdir()) == []


def test_convert_uses_a_given_name_and_reports_warnings(pine_dash):
    src = GOOD + 'bgcolor(close > open ? color.green : na)\n'
    status, body, _ = pine_dash.post("/api/pine/convert", {"source": src, "name": "my_sma"})
    data = as_json(body)
    assert status == 200 and data["name"] == "my_sma" and "NAME = 'my_sma'" in data["code"]
    assert any("bgcolor" in w for w in data["warnings"])


def test_syntax_error_is_a_400_with_line_and_col(pine_dash):
    status, body, _ = pine_dash.post("/api/pine/convert", {"source": '//@version=5\nindicator("x")\nplot(close,\n'})
    data = as_json(body)
    assert status == 400 and (data["line"], data["col"]) == (3, 5) and "never closed" in data["error"]
    status, body, _ = pine_dash.post("/api/pine/convert", {"source": '//@version=5\nindicator("x")\nplot(foo(close))\n'})
    data = as_json(body)
    assert status == 400 and data["line"] == 3 and "unknown function" in data["error"]


def test_bad_bodies_and_names_are_400(pine_dash):
    for body in ({}, {"source": ""}, {"source": 5}, {"source": "x" * 61_000}):
        assert pine_dash.post("/api/pine/convert", body)[0] == 400, body
    for name in ("Bad", "1abc", "has space", "a-b", "x" * 41, "../evil", 5):
        status, payload, _ = pine_dash.post("/api/pine/save", {"source": GOOD, "name": name})
        assert status == 400, name
        assert "name" in as_json(payload)["error"]
    assert pine_dash.post("/api/pine/save", {"source": GOOD})[0] == 400        # a name is required to save
    assert pine_dash.post("/api/pine/convert", {"source": GOOD, "name": "Bad"})[0] == 400
    assert list(pine_dash.target.iterdir()) == []


def test_routes_need_the_page_token(pine_dash):
    assert pine_dash.post("/api/pine/convert", {"source": GOOD}, token=False)[0] == 403
    assert pine_dash.post("/api/pine/save", {"source": GOOD, "name": "abc"}, token=False)[0] == 403


def test_save_writes_a_loadable_file(pine_dash):
    status, body, _ = pine_dash.post("/api/pine/save", {"source": GOOD, "name": "tiny_sma"})
    data = as_json(body)
    assert status == 200 and data["ok"] is True and data["name"] == "tiny_sma"
    target = pine_dash.target / "tiny_sma.py"
    assert Path(data["path"]) == target and target.is_file()
    code = target.read_text(encoding="utf-8")
    assert code.startswith(pine.GENERATED_MARKER) and code.isascii()
    # the same loader the dashboard uses on indicators_ext accepts it
    import importlib.util
    spec = importlib.util.spec_from_file_location("zz_saved_pine", target)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    result = indicator_plugins.run(module, pine.synthetic_candles(), {"len": 3})
    assert result["series"][0]["points"] and result["name"] == "tiny_sma"
    # saving again over its own output is fine
    assert pine_dash.post("/api/pine/save", {"source": GOOD, "name": "tiny_sma"})[0] == 200
    assert [p.name for p in pine_dash.target.glob("*.py")] == ["tiny_sma.py"]


def test_save_refuses_to_overwrite_a_file_it_did_not_generate(pine_dash):
    mine = pine_dash.target / "mine.py"
    mine.write_text("# my own indicator\nNAME = 'mine'\n", encoding="utf-8")
    status, body, _ = pine_dash.post("/api/pine/save", {"source": GOOD, "name": "mine"})
    assert status == 400 and "already exists" in as_json(body)["error"]
    assert mine.read_text(encoding="utf-8") == "# my own indicator\nNAME = 'mine'\n"
    blank = pine_dash.target / "blank.py"
    blank.write_text("", encoding="utf-8")
    assert pine_dash.post("/api/pine/save", {"source": GOOD, "name": "blank"})[0] == 400


def test_save_does_not_write_a_script_that_cannot_convert(pine_dash):
    status, body, _ = pine_dash.post("/api/pine/save", {"source": "plot(zzz)\n", "name": "broken"})
    assert status == 400 and as_json(body)["line"] == 1
    assert not (pine_dash.target / "broken.py").exists()


def test_save_does_not_write_code_that_fails_its_test_run(pine_dash, monkeypatch):
    # a converter bug must never leave a broken plugin behind
    real = pine._convert

    def broken(source, name):
        result = real(source, name)
        result.code = result.code.replace("def compute(candles, params):", "def compute(candles, params):\n    raise ZeroDivisionError('boom')")
        return result

    monkeypatch.setattr(pine, "_convert", broken)
    status, body, _ = pine_dash.post("/api/pine/save", {"source": GOOD, "name": "boom"})
    assert status == 400 and "test run" in as_json(body)["error"]
    assert not (pine_dash.target / "boom.py").exists()
    status, body, _ = pine_dash.post("/api/pine/convert", {"source": GOOD})
    assert status == 200 and any("test run" in w for w in as_json(body)["warnings"])


def test_examples_route_lists_every_example(pine_dash):
    status, body, _ = pine_dash.get("/api/pine/examples")
    examples = as_json(body)["examples"]
    assert status == 200
    names = {e["name"] for e in examples}
    assert {"sma_cross", "bollinger", "rsi", "supertrend", "custom_function", "macd"} <= names
    for e in examples:
        assert e["title"] and e["source"].startswith("//@version")
        status, body, _ = pine_dash.post("/api/pine/convert", {"source": e["source"]})
        assert status == 200 and as_json(body)["warnings"] == [], e["name"]


def test_marker_words_never_appear_in_the_generated_examples():
    for e in as_json_examples():
        text = e["source"].lower()
        assert " buy" not in text and " sell" not in text and "signal" not in text


def as_json_examples():
    out = []
    for path in sorted(pine.EXAMPLES_DIR.glob("*.pine")):
        out.append({"name": path.stem, "source": path.read_text(encoding="utf-8")})
    return out
